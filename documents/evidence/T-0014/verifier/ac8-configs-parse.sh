#!/bin/bash
# T-0014-AC8 (Verifier): every .bazelrc config parses on Bazel 9.3.0, and
# negative controls (undefined config, unknown flag) fail.
#   MC_BAZELISK=<wrapper that adds --output_base> ac8-configs-parse.sh
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
cd "$ROOT"
PAT="Unrecognized option|unknown option|is not defined in any .rc file|Config value .* is not defined|ERROR: --"
run() {
  local log rc bad
  log=$(tool/bazelw "$@" 2>&1 | tr '\r' '\n'); rc=${PIPESTATUS[0]}
  bad=$(printf '%s\n' "$log" | grep -a -c -E "$PAT")
  echo "| \`tool/bazelw $*\` | $rc | $bad | $(printf '%s\n' "$log" | grep -a -E '^ERROR' | head -1 | cut -c1-140) |"
}
echo "| Command | Exit | Unknown option / undefined config lines | First ERROR line |"
echo "|---|---|---|---|"
run build --nobuild --config=lint //spike/...
run build --nobuild --config=ci --config=cold //spike/...
run build --nobuild --config=budget16 //spike/...
run build --nobuild --config=budget16_8c //spike/...
run build --nobuild --config=profile //spike/...
run build --nobuild --config=remote-cache //spike/...
run build --nobuild --config=sim //spike/hello:hello_ios
run build --nobuild --config=device //spike/hello:hello_ios
run build --nobuild --config=device-profile //spike/...
run test --nobuild --config=app //spike/...
run build --nobuild --config=bogus_verifier_cfg //spike/...
run build --nobuild --bogus_verifier_flag //spike/...
run --budget16 build --nobuild //spike/...
